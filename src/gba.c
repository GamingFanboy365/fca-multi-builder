int gba_has_logo(const uint8_t *rom, size_t len)
{
    return len >= GBA_HEADER_SIZE && !memcmp(rom + 4, gba_logo, sizeof gba_logo);
}

uint8_t gba_header_checksum(const uint8_t *rom)
{
    unsigned sum = 0;
    int i;
    for (i = 0xA0; i <= 0xBC; i++)
        sum += rom[i];
    return (uint8_t)(-(int)(sum + 0x19));
}

int gba_checksum_ok(const uint8_t *rom, size_t len)
{
    return len >= GBA_HEADER_SIZE && rom[0xBD] == gba_header_checksum(rom);
}

static void put_field(uint8_t *dst, const char *src, size_t n)
{
    size_t i;
    memset(dst, 0, n);
    for (i = 0; i < n && src[i]; i++)
        dst[i] = (uint8_t)src[i];
}

void gba_fix_header(uint8_t *rom, size_t len, const char *title,
                    const char *code, const char *maker)
{
    uint8_t keep_code[4], keep_maker[2];
    if (len < GBA_HEADER_SIZE)
        return;
    memcpy(keep_code, rom + 0xAC, 4);
    memcpy(keep_maker, rom + 0xB0, 2);
    memcpy(rom + 4, gba_logo, sizeof gba_logo);
    /* NES2FCA rewrote the whole 32-byte block 0xA0..0xBF. */
    memset(rom + 0xA0, 0, 0x20);
    put_field(rom + 0xA0, title ? title : "", 12);
    if (code)
        put_field(rom + 0xAC, code, 4);
    else
        memcpy(rom + 0xAC, keep_code, 4);
    if (maker)
        put_field(rom + 0xB0, maker, 2);
    else
        memcpy(rom + 0xB0, keep_maker, 2);
    rom[0xB2] = 0x96;
    rom[0xBD] = gba_header_checksum(rom);
}
